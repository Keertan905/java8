package datatype;

public class IntegerLitters {
public static void main(String[] args) {
	int a=0B100;
	System.out.println(a);
	int b=045;
	System.out.println(b);
	int c =0x44;
	System.out.println(c);
	int d=10000000;
	int e =1_00_000_000;
	long f=62_00_45_85_45l;
	float g = 99_99_99_99_99f;
	System.out.println("sweta");
	System.out.println(d);
	System.out.println("\'Sweta\'");
	System.out.println("\"sweta\"");
	System.out.println("\\");
	System.out.println("\\\\\\\\");   // escape sequence
	System.out.println("\\\\");
}
}
